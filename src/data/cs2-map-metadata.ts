export const findCs2Map = (name: string) => CS2_MAP_METADATA.find((map) => map.name === name)

export const scaleDemoCoordinate = (map: Cs2MapMetadata, imageSize: number, x: number, y: number) => ({
  x: ((x - map.positionX) / map.scale) * imageSize / map.radarSize,
  y: ((map.positionY - y) / map.scale) * imageSize / map.radarSize,
})

export const mapLayer = (map: Cs2MapMetadata, z: number): 'upper' | 'lower' => z < map.thresholdZ ? 'lower' : 'upper'
